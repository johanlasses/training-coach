"""Fake Anthropic Messages API: streams schema-valid replies for plan, chat, ride feedback, the daily check-in and analysis.

The purpose is read from the requested JSON schema. /_dev/mode switches failure behaviour, /_dev/requests shows
what the app sent (to check what reached the prompt)."""
from __future__ import annotations

import json
import re
from datetime import date

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, StreamingResponse

app = FastAPI()
state = {"mode": "ok", "requests": []}


def steps_for(minutes: int) -> list[dict]:
    base = {"duration_s": 0, "power_low": 0, "power_high": 0, "repeat": 0, "on_s": 0, "off_s": 0, "on_power": 0,
            "off_power": 0, "cadence": 0, "text": "", "cues": []}
    return [base | {"type": "warmup", "duration_s": 600, "power_low": 0.5, "power_high": 0.65},
            base | {"type": "steady", "duration_s": (minutes - 20) * 60, "power_low": 0.65, "power_high": 0.65,
                    "text": "Easy and smooth"},
            base | {"type": "cooldown", "duration_s": 600, "power_low": 0.6, "power_high": 0.45}]


def day(iso: str, minutes: int) -> dict:
    d = {"date": iso, "kind": "rest", "title": "Rest", "description": "Rest day.", "duration_min": 0,
         "intensity": "recovery", "target_tss": 0, "bike": "none", "terrain": "", "steps": [],
         "test_protocol": "none"}
    if minutes >= 45:
        return d | {"kind": "zwift", "title": "Endurance spin", "description": "Easy aerobic ride.",
                    "duration_min": 60, "intensity": "endurance", "target_tss": 50, "bike": "trainer",
                    "steps": steps_for(60)}
    return d


def fenced_json(text: str) -> dict:
    m = re.search(r"```json\n(.*?)\n```", text, re.S)
    return json.loads(m.group(1)) if m else {}


def last_user_text(messages: list[dict]) -> str:
    c = messages[-1]["content"]
    return c if isinstance(c, str) else " ".join(b.get("text", "") for b in c if isinstance(b, dict))


def plan_reply(messages: list[dict]) -> dict:
    first = next(m for m in messages if m["role"] == "user")
    text = first["content"] if isinstance(first["content"], str) else first["content"][0]["text"]
    dates = re.search(r"Plan these days: ([\d, -]+)\.", text).group(1).split(", ")
    avail = list(fenced_json(text).get("snapshot", {}).get("availability", {}).values())
    retry = len(messages) > 1
    bad = state["mode"] == "invalid-plan-always" or (state["mode"] == "invalid-plan" and not retry)
    days = [day(d, avail[date.fromisoformat(d).weekday()] if i % 2 == 0 and len(avail) == 7 else 0)
            for i, d in enumerate(dates)]
    if bad:
        days = days[:-1]  # "days must be exactly these dates"
    return {"week_focus": "Aerobic base (dev fake)", "rationale": "Generated by the dev fake Anthropic API.",
            "days": days}


def chat_reply(messages: list[dict]) -> dict:
    text = last_user_text(messages)
    ctx = fenced_json(text)
    ask = text.split("```json")[0].lower()
    out = {"reply": "Dev fake coach here. I saw your message.", "plan_changes": [], "add_notes": [],
           "remove_note_ids": [], "remember": [], "forget_memory_ids": []}
    if "rest" in ask and ctx.get("open_dates"):
        out["plan_changes"] = [day(ctx["open_dates"][0], 0)]
        out["reply"] = f"Made {ctx['open_dates'][0]} a rest day. Apply it with the button."
    if "remember" in ask:
        out["remember"] = ["Dev fact: " + ask.strip()[:80]]
    return out


def feedback_reply() -> dict:
    return {"headline": "Solid steady ride", "notification": "Dev fake feedback: power held steady. Eat, then easy tomorrow.",
            "detail": "**Dev fake.** Execution looked fine.\n\n- Steady power\n- Recover well"}


def reply_for(body: dict) -> str:
    schema = (body.get("output_config") or {}).get("format", {}).get("schema") or {}
    props = schema.get("properties", {})
    messages = body["messages"]
    if "week_focus" in props:
        return json.dumps(plan_reply(messages))
    if "plan_changes" in props:
        return json.dumps(chat_reply(messages))
    if "headline" in props:
        return json.dumps(feedback_reply())
    if list(props) == ["message"]:
        return json.dumps({"message": "Dev fake check-in: yesterday is in the bank. Today, ride it as planned."})
    return "# Analysis (dev fake)\n\nVolume and intensity look reasonable.\n\n## Recommendations\n- Keep the easy days easy.\n"


def sse(model: str, text: str, stop_reason: str = "end_turn") -> str:
    events = [
        ("message_start", {"type": "message_start", "message": {
            "id": "msg_dev", "type": "message", "role": "assistant", "model": model, "content": [],
            "stop_reason": None, "stop_sequence": None, "usage": {"input_tokens": 1200, "output_tokens": 0}}}),
        ("content_block_start", {"type": "content_block_start", "index": 0, "content_block": {"type": "text", "text": ""}}),
        ("content_block_delta", {"type": "content_block_delta", "index": 0, "delta": {"type": "text_delta", "text": text}}),
        ("content_block_stop", {"type": "content_block_stop", "index": 0}),
        ("message_delta", {"type": "message_delta", "delta": {"stop_reason": stop_reason, "stop_sequence": None},
                           "usage": {"output_tokens": 400}}),
        ("message_stop", {"type": "message_stop"}),
    ]
    return "".join(f"event: {e}\ndata: {json.dumps(d)}\n\n" for e, d in events)


@app.get("/v1/models/{model}")
def model_info(model: str):
    return {"id": model, "type": "model", "display_name": model, "created_at": "2026-01-01T00:00:00Z"}


@app.post("/v1/messages")
async def messages(request: Request):
    body = await request.json()
    state["requests"].append({"model": body.get("model"), "system": body.get("system"), "messages": body["messages"],
                              "output_config": body.get("output_config")})
    mode = state["mode"]
    if mode == "429":
        return JSONResponse({"type": "error", "error": {"type": "rate_limit_error", "message": "dev rate limit"}},
                            status_code=429, headers={"retry-after": "1"})
    if mode == "500":
        return JSONResponse({"type": "error", "error": {"type": "api_error", "message": "dev boom"}}, status_code=500)
    if mode == "refusal":
        return StreamingResponse(iter([sse(body["model"], "", "refusal")]), media_type="text/event-stream")
    return StreamingResponse(iter([sse(body["model"], reply_for(body))]), media_type="text/event-stream")


@app.post("/_dev/mode")
def set_mode(mode: str = "ok"):
    state["mode"] = mode
    return state["mode"]


@app.get("/_dev/requests")
def requests():
    return state["requests"]


@app.post("/_dev/reset")
def reset():
    state.update(mode="ok", requests=[])
    return {"ok": True}
